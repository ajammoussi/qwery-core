import type { CompactionStrategy, StrategyOriginals, StrategyContext } from '../strategy.js';
import type { ProcessInput, SessionCompaction } from '@qwery/agent-factory-sdk';
import { ZoneContextManager } from '../../zone-architecture/zone-context-manager.js';
import type { ZoneSegment } from '../../zone-architecture/types.js';
import {
  createZoneSegment,
  extractQueryFromMessages,
  extractTextFromMessage,
  isUserCorrection,
} from '../../zone-architecture/zone-strategy-base.js';
import { v4 as uuidv4 } from 'uuid';


export interface FourZoneConfig {
  activeWindow?: {
    enabled?: boolean;
    maxTurns?: number;
  };
  compressedArchive?: {
    enabled?: boolean;
    maxSegments?: number;
    retrievalTopK?: number;
  };
}

export function with4Zone(
  baseStrategy: CompactionStrategy,
  config?: FourZoneConfig,
): CompactionStrategy {
  return {
    name: baseStrategy.name,
    // The factory receives a fresh context / originals for each session.
    factory: (ctx: StrategyContext, originals: StrategyOriginals) => {
      const baseHooks = baseStrategy.factory(ctx, originals);

      // Mutable flag set by `isOverflow` and read by `process`.
      let overflowFlag = false;

      // Per-session / factory-instance state
      const zoneManager = new ZoneContextManager({
        activeWindow: {
          enabled: config?.activeWindow?.enabled ?? true,
          maxTurns: config?.activeWindow?.maxTurns ?? 6,
        },
        entityState: {
          enabled: true,
          maxTokens: 400,
        },
        compressedArchive: {
          enabled: config?.compressedArchive?.enabled ?? true,
          maxSegments: config?.compressedArchive?.maxSegments ?? 50,
          retrievalTopK: config?.compressedArchive?.retrievalTopK ?? 3,
        },
      });
      const processedMessageIds = new Set<string>();

      // push raw messages into Active Window (and Compressed Archive on overflow)
      function processMessagesIntoZones(
        messages: ProcessInput['messages'],
        mgr: ZoneContextManager,
      ): void {
        const entityStateTracker = mgr.getEntityStateTracker();
        let localTurnNumber = mgr.getTurnCounter();

        for (const msg of messages) {
          if (msg.id && processedMessageIds.has(msg.id)) continue;
          if (msg.metadata?.assembled) continue; // Skip messages generated by this wrapper
          if (msg.id) processedMessageIds.add(msg.id);

          const content = extractTextFromMessage(msg);
          const isCorrection = isUserCorrection(msg);

          if (msg.role === 'user') {
            localTurnNumber = mgr.incrementTurnCounter();
            mgr.addToZoneC(
              createZoneSegment(content, 'active-window', {
                messageId: msg.id,
                turnNumber: localTurnNumber,
                segmentType: isCorrection ? 'user_correction' : 'user_turn',
              }),
            );
            entityStateTracker.extractFromText(content, isCorrection);
          } else if (msg.role === 'assistant') {
            mgr.addToZoneC(
              createZoneSegment(content, 'active-window', {
                messageId: msg.id,
                turnNumber: localTurnNumber,
                segmentType: 'assistant_turn',
              }),
            );
            entityStateTracker.extractFromText(content, false);

            // Schema extraction from tool outputs + filter extraction from runQuery inputs.
            // Two message formats co-exist:
            //   - Repository format (persisted messages): { type: 'tool-runQuery', input: { query } }
            //   - UIMessage format (in-memory from AI SDK): { type: 'tool-invocation', toolInvocation: { toolName, args } }
            // UIMessages store parts at msg.parts; persisted messages use msg.content.parts
            const parts = (msg.content as { parts?: any[] })?.parts ?? (msg as any).parts ?? [];
            const runQueryCalls: Array<{ toolName: string; toolInput: Record<string, unknown> }> = [];
            for (const part of parts) {
              const partType = typeof part.type === 'string' ? part.type : '';

              if (partType === 'tool-invocation' && part.toolInvocation) {
                // UIMessage format: { type: 'tool-invocation', toolInvocation: { toolName, args, state, result } }
                const inv = part.toolInvocation as { toolName?: string; args?: Record<string, unknown>; state?: string; result?: unknown };
                const invName = inv.toolName ?? '';
                if (invName === 'getSchema' || invName === 'describeTables') {
                  if (inv.state === 'result') {
                    const schemaText = typeof inv.result === 'string' ? inv.result : JSON.stringify(inv.result ?? '');
                    mgr.populateZoneA(schemaText, []);
                  }
                } else if (invName === 'runQuery' && inv.args && typeof inv.args === 'object') {
                  runQueryCalls.push({ toolName: 'runQuery', toolInput: inv.args });
                }
              } else {
                // Repository format: { type: 'tool-runQuery', toolName?: string, input?: {...}, output?: ... }
                const toolName = part.toolName || (partType.startsWith('tool-') ? partType.slice(5) : '');
                if (toolName === 'getSchema' || toolName === 'describeTables') {
                  const schemaText =
                    typeof part.output === 'string'
                      ? part.output
                      : JSON.stringify(part.output ?? '');
                  mgr.populateZoneA(schemaText, []);
                } else if (toolName === 'runQuery' && part.input && typeof part.input === 'object') {
                  runQueryCalls.push({ toolName: 'runQuery', toolInput: part.input as Record<string, unknown> });
                }
              }
            }
            if (runQueryCalls.length > 0) {
              entityStateTracker.extractFromToolCalls(runQueryCalls);
            }
          }
        }

        mgr.syncEntityStateToZoneB();
      }

      async function fetchSummaryFromRepository(input: ProcessInput): Promise<string | null> {
        if (!input.repositories.message) return null;

        try {
          const conversation = await input.repositories.conversation.findBySlug(input.conversationSlug);
          if (!conversation) return null;

          const messages = await input.repositories.message.findByConversationId(conversation.id);
          // Look for the latest assistant message with summary: true
          const summaryMsg = [...messages].reverse().find(m => {
            const meta = m.metadata as { summary?: boolean } | undefined;
            return m.role === 'assistant' && meta?.summary === true;
          });

          if (!summaryMsg) return null;

          const parts = (summaryMsg.content as { parts?: any[] })?.parts ?? [];
          return parts.find(p => p.type === 'text')?.text ?? null;
        } catch (e) {
          console.warn('Failed to fetch summary from repository:', e);
          return null;
        }
      }

      // Overflow
      const isOverflow: typeof SessionCompaction.isOverflow = async (input) => {
        if (input && (input as any).messages) {
          processMessagesIntoZones((input as any).messages, zoneManager);
        }
        const totalTokens = zoneManager.getTotalAssembledTokens();

        // Compute the available headroom from the hosting model. 
        const modelContext =
          typeof input?.model === 'string'
            ? undefined 
            : input?.model?.limit?.context;

        const TOKEN_SOFT_LIMIT =
          typeof modelContext === 'number' && modelContext > 0
            ? Math.floor(modelContext * 0.6)
            : 8000;

        const baseOverflow = baseHooks.isOverflow
          ? await baseHooks.isOverflow(input)
          : false;

        overflowFlag = totalTokens > TOKEN_SOFT_LIMIT || baseOverflow;
        return overflowFlag;
      };

      // Process
      const process: typeof originals.process = async (input) => {
        processMessagesIntoZones(input.messages, zoneManager);
        const query = extractQueryFromMessages(input.messages);
        
        // ---- ALWAYS replace raw messages with assembled 4-zone context ----
        input.messages = buildAssembledMessages(zoneManager, query, input.parentID);

        // No overflow this turn → pass through to the agent normally
        if (!overflowFlag) {
          return await originals.process(input);
        }

        // Overflow fired → invoke base strategy compression on Compressed Archive
        const zoneD = zoneManager.getContext().zoneD;

        if (zoneD.length > 0) {
          // Build a synthetic input containing ONLY Compressed Archive segments so the
          // base strategy compresses the archive, not the whole session.
          const syntheticInput = buildZoneDOnlyInput(zoneD, input, query);

          // Delegate to base strategy
          await baseHooks.process(syntheticInput);

          // Capture the actual summary from the repository
          const summary = await fetchSummaryFromRepository(input);
          if (summary) {
            zoneManager.getContext().zoneD = [
              createZoneSegment(summary, 'compressed-archive', {
                segmentType: 'compacted_archive',
              }),
            ];
          } else {
            // Fallback if summary fetch failed
            zoneManager.getContext().zoneD = [
              createZoneSegment(
                `Compressed Archive compressed: ${zoneD.length} segments consolidated.`,
                'compressed-archive',
                { segmentType: 'compacted_archive' },
              ),
            ];
          }
        }

        // Write compaction event to repository (once per overflow event)
        const assembly = zoneManager.assembleContext(query);
        await writeCompactionSummary(zoneManager, assembly, input);

        // Reset flag for next turn
        overflowFlag = false;

        return 'continue' as const;
      };

      const getState = (options?: { prune?: boolean; excludeRaw?: boolean }) => {
        const context = zoneManager.getContext();
        const zoneCTurnNumbers = [...new Set(context.zoneC.map((s) => s.metadata?.turnNumber).filter((t): t is number => t !== undefined))]
          .sort((a, b) => a - b);
        const zoneCLatest = context.zoneC[context.zoneC.length - 1];
        const zoneDLatest = context.zoneD[context.zoneD.length - 1];

        // Extract Active Window segment types for analysis
        const zoneCSegmentTypes = context.zoneC.map(s => s.metadata?.segmentType || 'unknown');
        const userTurns = zoneCSegmentTypes.filter(t => t === 'user_turn' || t === 'user_correction').length;
        const assistantTurns = zoneCSegmentTypes.filter(t => t === 'assistant_turn').length;

        // Extract Compressed Archive segment types for analysis
        const zoneDSegmentTypes = context.zoneD.map(s => s.metadata?.segmentType || 'unknown');
        const archivedSummaries = zoneDSegmentTypes.filter(t => t === 'compacted_archive').length;
        // Fix: Count turns and corrections in archive
        const archivedTurns = zoneDSegmentTypes.filter(t => t.includes('turn') || t === 'user_correction').length;

        const parseStructuredContent = (content: string) => {
          const lines = content.split('\n');
          const firstLine = lines[0];
          const rest = lines.slice(1);
          const hasHeader = !!(firstLine?.startsWith('[') && firstLine?.endsWith(']'));
          const header = hasHeader ? firstLine : undefined;
          const body = (hasHeader ? rest.join('\n') : content).trim();
          const truncated = body.endsWith('...');
          let parsed: unknown = null;
          let parseError: string | undefined;
          
          // Only parse if not pruning or if explicit raw exclusion (meaning we want parsed)
          if (body && !options?.prune) {
            try {
              parsed = JSON.parse(body);
            } catch {
              parseError = 'invalid_json';
            }
          }
          
          return {
            header,
            raw: options?.excludeRaw ? undefined : (body || content),
            parsed: options?.prune ? undefined : parsed,
            parseError,
            truncated,
          };
        };

        const parsedSchemaSegments = context.zoneA.map((s) => {
          const structured = parseStructuredContent(s.content);
          return {
            type: s.metadata?.segmentType || 'unknown',
            content: structured,
            tokens: s.tokens,
          };
        });

        const parsedEntitySegments = context.zoneB.map((s) => {
          const structured = parseStructuredContent(s.content);
          return {
            type: s.metadata?.segmentType || 'unknown',
            content: structured,
            tokens: s.tokens,
          };
        });

        return {
          // Schema & Constraints (Full Content)
          schemaAndConstraints: {
            segments: parsedSchemaSegments,
            totalSegments: context.zoneA.length,
            totalTokens: context.zoneA.reduce((sum, s) => sum + s.tokens, 0),
            description: 'Schema definition, column descriptions, and global constraints (frozen, never compressed)',
          },

          // Entity State (Full Content)
          entityState: {
            segments: parsedEntitySegments,
            totalSegments: context.zoneB.length,
            totalTokens: context.zoneB.reduce((sum, s) => sum + s.tokens, 0),
            description: 'Rolling JSON tracking session state: tables, filters, columns, aggregations, threads (updated every turn)',
            parsedState: options?.prune 
              ? undefined 
              : (parsedEntitySegments[0]?.content as { parsed?: Record<string, unknown> })?.parsed,
          },

          // Active Window (Summary Only - avoid redundancy)
          activeWindow: {
            turnNumbers: zoneCTurnNumbers,
            messageCount: zoneCTurnNumbers.length,
            segmentComposition: {
              userTurns,
              assistantTurns,
              totalSegments: context.zoneC.length,
            },
            latestMessagePreview: zoneCLatest ? zoneCLatest.content.slice(0, 200) : '',
            totalTokens: context.zoneC.reduce((sum, s) => sum + s.tokens, 0),
            description: `Last ${context.config.activeWindow.maxTurns} turns in full fidelity (not serialized to avoid redundancy with turns array)`,
          },

          // Compressed Archive (Summary Only - avoid redundancy)
          compressedArchive: {
            segmentCount: context.zoneD.length,
            segmentComposition: {
              compactedArchives: archivedSummaries,
              archivedTurns,
              totalSegments: context.zoneD.length,
            },
            latestSegmentPreview: zoneDLatest ? zoneDLatest.content.slice(0, 200) : '',
            totalTokens: context.zoneD.reduce((sum, s) => sum + s.tokens, 0),
            description: `Older turns evicted from active window (max ${context.config.compressedArchive.maxSegments} segments, oldest evicted first)`,
          },

          // Overall Context Statistics
          summary: {
            totalZoneTokens: context.zoneA.reduce((sum, s) => sum + s.tokens, 0) +
                             context.zoneB.reduce((sum, s) => sum + s.tokens, 0) +
                             context.zoneC.reduce((sum, s) => sum + s.tokens, 0) +
                             context.zoneD.reduce((sum, s) => sum + s.tokens, 0),
            zoneTokens: {
              schemaAndConstraints: context.zoneA.reduce((sum, s) => sum + s.tokens, 0),
              entityState: context.zoneB.reduce((sum, s) => sum + s.tokens, 0),
              activeWindow: context.zoneC.reduce((sum, s) => sum + s.tokens, 0),
              compressedArchive: context.zoneD.reduce((sum, s) => sum + s.tokens, 0),
            },
            activeWindow: {
              maxTurns: context.config.activeWindow.maxTurns,
              currentTurns: zoneCTurnNumbers.length,
              isFull: zoneCTurnNumbers.length >= context.config.activeWindow.maxTurns,
            },
            archive: {
              maxSegments: context.config.compressedArchive.maxSegments,
              currentSegments: context.zoneD.length,
              isFull: context.zoneD.length >= context.config.compressedArchive.maxSegments,
            },
          },
        };
      };

      return {
        isOverflow,
        process,
        prune: baseHooks.prune,
        getState,
      };
    },
  };
}

// construct assembled messages from 4-zone context
function buildAssembledMessages(
  zoneManager: ZoneContextManager,
  query: string,
  parentID: string,
): ProcessInput['messages'] {
  const context = zoneManager.getContext();
  const messages: ProcessInput['messages'] = [];

  // 1. Initial 4-Zone System Prompt
  messages.push({
    role: 'system',
    id: uuidv4(),
    content: {
      parts: [
        {
          type: 'text',
          text: '4-ZONE CONTEXT: Below is your current session state. The "History of the Model" section summarizes past interactions. The "Active Window" contains recent messages. Do NOT assume access to history outside these zones.',
        },
      ],
    },
    metadata: { assembled: true },
  } as any);

  // 2. Schema & Constraints (Role: system)
  if (context.zoneA.length > 0) {
    // Schema & Constraints segments are already prefixed with section headers
    const schemaContent = context.zoneA.map((s) => s.content).join('\n\n');
    messages.push({
      role: 'system',
      id: uuidv4(),
      content: {
        parts: [{ type: 'text', text: schemaContent }],
      },
      metadata: { assembled: true },
    } as any);
  }

  // 3. Entity State (Role: system)
  if (context.zoneB.length > 0) {
    // Entity State content already includes header from syncEntityStateToZoneB
    const entityStateContent = context.zoneB.map((s) => s.content).join('\n\n');
    messages.push({
      role: 'system',
      id: uuidv4(),
      content: {
        parts: [{ type: 'text', text: entityStateContent }],
      },
      metadata: { assembled: true },
    } as any);
  }

  // 4. Compressed Archive (Role: assistant)
  const { retrievedSegments } = zoneManager.retrieveFromZoneD(query);
  if (retrievedSegments.length > 0) {
    const historyContent = retrievedSegments.map((s) => s.content).join('\n\n');
    messages.push({
      role: 'assistant',
      id: uuidv4(),
      content: {
        parts: [{ type: 'text', text: `[HISTORY OF THE MODEL]\n${historyContent}` }],
      },
      metadata: { assembled: true },
    } as any);
  }

  // 5. Active Window (Role: original)
  for (const segment of context.zoneC) {
    // Skip the current query if it's already in Active Window to avoid duplicates
    if (segment.metadata?.messageId === parentID) continue;

    const role = segment.metadata?.segmentType?.includes('user') ? 'user' : 'assistant';
    messages.push({
      role: role as any,
      id: segment.metadata?.messageId ?? uuidv4(),
      content: {
        parts: [{ type: 'text', text: segment.content }],
      },
      metadata: { assembled: true },
    } as any);
  }

  // 6. Current Query (Role: user, ID: parentID)
  if (query) {
    messages.push({
      role: 'user',
      id: parentID,
      content: {
        parts: [{ type: 'text', text: query }],
      },
      metadata: { assembled: true },
    } as any);
  }

  return messages;
}

function buildZoneDOnlyInput(
  zoneDSegments: ReadonlyArray<ZoneSegment>,
  originalInput: ProcessInput,
  currentQuery?: string,
): ProcessInput {
  const compressedContent = zoneDSegments
    .map((s, i) => `--- Historical Segment ${i + 1} ---\n${s.content}`)
    .join('\n\n');

  const systemText = currentQuery
    ? `[CURRENT QUERY]: ${currentQuery}\n\nSummarize the following history of the model. Focus on SQL entities, active filters, and previous intent.`
    : 'Summarize the following history of the model. Focus on SQL entities, active filters, and previous intent.';

  return {
    ...originalInput,
    messages: [
      {
        id: uuidv4(),
        role: 'system' as const,
        content: {
          parts: [
            {
              type: 'text' as const,
              text: systemText,
            },
          ],
        },
      },
      {
        id: originalInput.parentID,
        role: 'user' as const,
        content: {
          parts: [{ type: 'text' as const, text: compressedContent }],
        },
      },
    ] as ProcessInput['messages'],
  };
}

// NOTE: writeCompactionSummary is currently unused — the base strategy's
//       process() already writes a summary to the repository when it runs.
//       Keep for potential future use when a base strategy does NOT write
//       its own summary.
// persist a single compaction summary message to the repository
async function writeCompactionSummary(
  zoneManager: ZoneContextManager,
  assembly: { assembledContext: string; totalTokens: number },
  input: ProcessInput,
): Promise<void> {
  const messages = input.messages;
  const repositories = input.repositories as {
    message?: {
      create: (data: {
        id: string;
        conversationId: string;
        role: 'assistant';
        content: { parts: Array<{ type: string; text: string }> };
        metadata: { summary: boolean; type: string; tokens?: { output: number } };
        createdAt: Date;
        updatedAt: Date;
        createdBy: string;
        updatedBy: string;
      }) => Promise<unknown>;
    };
  };

  const conversationId =
    (messages[0] as { conversationId?: string } | undefined)?.conversationId ?? input.parentID;

  if (!repositories?.message) return;

  const fullContextMessage = `4-ZONE CONTEXT COMPACTION\n\n${assembly.assembledContext}`;

  try {
    await repositories.message.create({
      id: uuidv4(),
      conversationId: String(conversationId),
      role: 'assistant',
      content: {
        parts: [{ type: 'text', text: fullContextMessage }],
      },
      metadata: {
        summary: true,
        type: 'compaction',
        tokens: { output: Math.ceil(fullContextMessage.length / 4) },
      },
      createdAt: new Date(),
      updatedAt: new Date(),
      createdBy: 'system',
      updatedBy: 'system',
    });
  } catch (error) {
    console.warn('Failed to persist 4-zone compaction summary:', error);
  }
}
